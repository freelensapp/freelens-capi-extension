// A context at the capture, with every controller available, and the inputs a case gives.
export function contextOf(inputs: Partial<StatusContext> = {}): StatusContext {
  return { now: CAPTURE, controllers: AVAILABLE_CONTROLLERS, ...inputs };
}

function conditionsOf(object: object): readonly Condition[] {
  const status = (object as { status?: { conditions?: readonly Condition[] } }).status;

  return status?.conditions ?? [];
}

// A copy of the object with its status changed.
export function withStatus<T extends object>(object: T, changes: Record<string, unknown>): T {
  return { ...object, status: { ...(object as { status?: object }).status, ...changes } };
}

// A copy of the object with its spec changed.
export function withSpec<T extends object>(object: T, changes: Record<string, unknown>): T {
  return { ...object, spec: { ...(object as { spec?: object }).spec, ...changes } };
}

// A copy of the object with its metadata changed.
export function withMetadata<T extends object>(object: T, changes: Record<string, unknown>): T {
  return { ...object, metadata: { ...(object as { metadata?: object }).metadata, ...changes } };
}

// A copy of the object with the condition of a type changed; the condition must be there.
export function withCondition<T extends object>(object: T, type: string, changes: Record<string, unknown>): T {
  const conditions = conditionsOf(object);

  if (!conditions.some((condition) => condition.type === type)) throw new Error(`no condition ${type} to change`);
  return withStatus(object, {
    conditions: conditions.map((condition) => (condition.type === type ? { ...condition, ...changes } : condition)),
  });
}

// A copy of the object with a condition added after the others.
export function withAddedCondition<T extends object>(object: T, condition: Record<string, unknown>): T {
  return withStatus(object, { conditions: [...conditionsOf(object), condition] });
}

// A copy of the object with a condition of a third party, which no kind of the project writes, of the given status
// (SPEC-0001, H1): no fixture has one.
export function withThirdPartyCondition<T extends object>(object: T, status = "False"): T {
  return withAddedCondition(object, {
    type: "example.com/BackupReady",
    status,
    reason: status === "True" ? "BackupReady" : "BackupFailed",
    message: "",
    lastTransitionTime: "2025-12-31T23:59:50Z",
    observedGeneration: 1,
  });
}

// A copy of the object without the condition of a type; the condition must be there.
export function withoutCondition<T extends object>(object: T, type: string): T {
  const conditions = conditionsOf(object);

  if (!conditions.some((condition) => condition.type === type)) throw new Error(`no condition ${type} to remove`);
  return withStatus(object, { conditions: conditions.filter((condition) => condition.type !== type) });
}

// A copy of the object without its status, or without a field of it.
export function withoutStatus<T extends object>(object: T): T {
  const { status: _, ...rest } = object as T & { status?: unknown };

  return rest as T;
}

// A condition at v1beta2 as the fixtures write it, observed at generation 1 unless it says otherwise.
function condition(
  type: string,
  status: "True" | "False" | "Unknown",
  reason: string,
  lastTransitionTime: string,
  message = "",
  observedGeneration: number | undefined = 1,
): Condition {
  return observedGeneration === undefined
    ? { type, status, lastTransitionTime, reason, message }
    : { type, status, observedGeneration, lastTransitionTime, reason, message };
}

// A deprecated condition of v1beta1, with its reason, its severity and its message when it has them.
function deprecatedCondition(
  type: string,
  status: string,
  lastTransitionTime: string,
  rest: { reason?: string; severity?: string; message?: string } = {},
): DeprecatedCondition {
  return { type, status, lastTransitionTime, ...rest };
}

