// development provider, trimmed to the fields that the rules of the model read. Each group is one state of the
// fixtures, `integration/fixtures/<state>/`, and each object keeps its name there. Times are kept as the fixtures
// keep them, as offsets from the moment of the capture, 2026-01-01T00:00:00Z, which is `CAPTURE`; a generation that
// the fixtures leave out is 1, as the API server writes it for a new object, and is written here. The other
// identifiers, which the API server adds, are left out, as the fixtures leave them out.
//
// A case that needs a state the project does not produce on demand changes one field of a copy, with the helpers
// below, and says which. The cases that read the fixture files themselves, with the table of "The fixtures of
// SPEC-0002 give these results", are in src/common/status/fixtures.test.ts.

